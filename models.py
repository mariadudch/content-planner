"""Модели данных: какие «вещи» существуют в программе.

- Idea — идея, как ты её написала (этап 1);
- ContentUnit — единица контента: идея + рубрика + формат (этап 2).
На следующих этапах добавим сам контент-план.
"""

from dataclasses import dataclass


@dataclass
class Idea:
    """Одна идея — то, что ты написала одной строкой в файле с идеями."""

    text: str      # текст идеи без служебных пометок («!», «- »), как ты его написала
    key: str       # «нормализованный» текст: по нему ищем повторы и сравниваем со словами-сигналами
    line_no: int   # номер строки в файле — чтобы в сообщениях можно было написать «строка 7»
    urgent: bool = False  # была ли пометка «!» в начале строки


@dataclass
class ContentUnit:
    """Единица контента: одна идея в одной рубрике и в одном формате.

    Из одной идеи получается несколько единиц — по одной на каждую пару «рубрика + формат».
    """

    idea: Idea             # из какой идеи получилась единица
    rubric: str            # название рубрики, например «Бьюти-находки»
    format_name: str       # название формата, например «Рилс»
    platforms: list[str]   # где публикуем, например ["Instagram", "Telegram"]
    matched: list[str]     # какие слова-сигналы совпали — объяснение, почему выбрана эта рубрика
