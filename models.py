"""Модели данных: какие «вещи» существуют в программе.

Пока здесь одна вещь — идея. На следующих этапах добавим единицу контента
(идея, разложенная на рубрику и формат) и сам контент-план.
"""

from dataclasses import dataclass


@dataclass
class Idea:
    """Одна идея — то, что ты написала одной строкой в файле с идеями."""

    text: str      # текст идеи без служебных пометок («!», «- »), как ты его написала
    key: str       # «нормализованный» текст: по нему ищем повторы и сравниваем со словами-сигналами
    line_no: int   # номер строки в файле — чтобы в сообщениях можно было написать «строка 7»
    urgent: bool = False  # была ли пометка «!» в начале строки
